import { GridFSBucket, MongoClient, type Db } from 'mongodb'

const DB_NAME = process.env.MONGODB_DB || 'atlas_document_hub'

/** Maps each DemoState collection to its MongoDB collection and natural id field. */
export const COLLECTIONS = {
  users: { name: 'users', idField: '_id' },
  roles: { name: 'roles', idField: '_id' },
  folders: { name: 'folders', idField: '_id' },
  documents: { name: 'documents', idField: '_id' },
  documentVersions: { name: 'document_versions', idField: '_id' },
  documentChunks: { name: 'document_chunks', idField: '_id' },
  auditEvents: { name: 'audit_events', idField: 'eventId' },
  outboxEvents: { name: 'outbox_events', idField: '_id' },
  generationRuns: { name: 'generation_runs', idField: '_id' },
} as const

export type CollectionKey = keyof typeof COLLECTIONS
export const COLLECTION_KEYS = Object.keys(COLLECTIONS) as CollectionKey[]
export const SETTINGS_COLLECTION = 'system_settings'
export const OBJECTS_BUCKET = 'objects'

declare global {
  var __adhMongoClient: Promise<MongoClient> | undefined
  var __adhIndexesReady: Promise<void> | undefined
}

export function isAtlasConfigured(): boolean {
  return !!process.env.MONGODB_URI
}

export function atlasDatabaseName(): string {
  return DB_NAME
}

function connect(): Promise<MongoClient> {
  const uri = process.env.MONGODB_URI
  if (!uri) throw new Error('MONGODB_URI is not configured')
  globalThis.__adhMongoClient ??= new MongoClient(uri, {
    appName: 'atlas-document-hub',
    serverSelectionTimeoutMS: 8000,
  })
    .connect()
    .catch((error) => {
      globalThis.__adhMongoClient = undefined
      throw error
    })
  return globalThis.__adhMongoClient
}

async function ensureIndexes(db: Db) {
  await Promise.all([
    db.collection(COLLECTIONS.documents.name).createIndex({ tenantId: 1, updatedAt: -1 }),
    db.collection(COLLECTIONS.documents.name).createIndex({ tenantId: 1, datasetId: 1 }),
    db.collection(COLLECTIONS.documentVersions.name).createIndex({ tenantId: 1, documentId: 1, versionNumber: 1 }),
    db.collection(COLLECTIONS.documentChunks.name).createIndex({ tenantId: 1, documentId: 1, chunkIndex: 1 }),
    db.collection(COLLECTIONS.auditEvents.name).createIndex({ tenantId: 1, occurredAt: -1 }),
    db.collection(COLLECTIONS.outboxEvents.name).createIndex({ tenantId: 1, createdAt: -1 }),
    db.collection(COLLECTIONS.generationRuns.name).createIndex({ tenantId: 1, datasetId: 1 }),
  ])
}

export async function getDb(): Promise<Db> {
  const client = await connect()
  const db = client.db(DB_NAME)
  globalThis.__adhIndexesReady ??= ensureIndexes(db).catch((error) => {
    globalThis.__adhIndexesReady = undefined
    throw error
  })
  await globalThis.__adhIndexesReady
  return db
}

export async function getBucket(): Promise<GridFSBucket> {
  return new GridFSBucket(await getDb(), { bucketName: OBJECTS_BUCKET })
}

/** Object keys are generated by the ingestion pipeline as `obj/<32 hex chars>`. */
export function isValidObjectKey(key: unknown): key is string {
  return typeof key === 'string' && /^obj\/[a-f0-9]{32}$/.test(key)
}
